def subject(label, lines, checks, answer, prompt=""):
    """lines: (latex, en, ur) for each rearrangement; checks prove the result by putting it back."""
    steps = [S(t, en, ur) for t, en, ur in lines[:-1]]
    t, en, ur = lines[-1]
    steps.append(S(t, en, ur, *checks))
    return P(label, steps, answer, prompt=prompt)


