def three_ways(label, eq, prompt):
    a = q_solve(label, eq, "factor", prompt)
    b = q_solve(label, eq, "square", prompt)
    c = q_solve(label, eq, "formula", prompt)
    head = lambda en, ur: T(en, ur)  # noqa: E731
    steps = ([head("Method 1: factorization.", "طریقہ 1: تجزی۔")] + a["steps"] +
             [head("Method 2: completing the square.", "طریقہ 2: مربع مکمل کرنا۔")] + b["steps"] +
             [head("Method 3: quadratic formula.", "طریقہ 3: دو درجی کلیہ۔")] + c["steps"])
    return P(label, steps, a["answer"], prompt=prompt)


