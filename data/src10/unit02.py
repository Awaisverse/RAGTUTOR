def lin_quad(label, line_y, quad_y, prompt):
    """y = line and y = quadratic: equate, solve, find y, draw both."""
    from _gen import Graph, factor_steps, pt_label
    from _quad import _graph_ranges
    poly = sp.expand(sp.sympify(quad_y, locals={"x": X}) - sp.sympify(line_y, locals={"x": X}))
    alg, xs = factor_steps(poly)
    pts = [(x0, sp.sympify(line_y, locals={"x": X}).subs(X, x0)) for x0 in xs]
    xr, yr = _graph_ranges([quad_y, line_y], xs)
    yr = (min(yr[0], min(float(p[1]) for p in pts) - 3), max(yr[1], max(float(p[1]) for p in pts) + 3))
    g = Graph(xr, yr)
    steps = [S(rf"y = {tex(line_y)},\quad y = {tex(quad_y)}", "Draw both graphs on the same axes.", "دونوں گراف ایک ہی محوروں پر بنائیں۔",
               draw=g.axes() + g.curve(line_y) + g.curve(quad_y)),
             S(rf"{tex(quad_y)} = {tex(line_y)}", "At the points of intersection both $y$ values are equal.", "نقاط تقاطع پر دونوں $y$ برابر ہیں۔")]
    steps += alg
    steps.append(S(r",\quad ".join(rf"x = {sp.latex(x0)} \Rightarrow y = {sp.latex(y0)}" for x0, y0 in pts),
                   "Put each $x$ in the linear equation to get $y$.", "ہر $x$ کو خطی مساوات میں رکھ کر $y$ معلوم کریں۔",
                   *[f"({quad_y}).subs(x, {ps(x0)}) == {ps(y0)}" for x0, y0 in pts],
                   draw=sum((g.point(float(x0), float(y0), pt_label(x0, y0)) for x0, y0 in pts), [])))
    ans = ", ".join(f"({sp.latex(x0)}, {sp.latex(y0)})" for x0, y0 in sorted(pts, key=lambda p: -p[0]))
    return P(label, steps, f"${ans}$", prompt=prompt)


