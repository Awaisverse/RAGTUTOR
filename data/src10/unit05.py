def x2_eq(v):
    """x^2 = v  ->  x = +- sqrt(v)."""
    def run():
        r = sp.sqrt(v)
        return [S(rf"x^2 = {sp.latex(v)} \Rightarrow x = \pm {sp.latex(r)}", "Take the square root (both signs).", "جذر لیں (دونوں علامات)۔",
                  f"({sp.sstr(r)})**2 == {ps(v)}")], [r, -r]
    return run


def exp_eq(base, power_coef, v):
    """base^(power_coef*x) = v  ->  x."""
    def run():
        k = sp.log(v, base)
        k = sp.nsimplify(k)
        x0 = k / power_coef
        pw = "x" if power_coef == 1 else f"{power_coef}x"
        return [S(rf"{base}^{{{pw}}} = {sp.latex(v)} = {base}^{{{sp.latex(k)}}} \Rightarrow {pw} = {sp.latex(k)} \Rightarrow x = {sp.latex(x0)}",
                  "Write the right side as a power of the same base and equate the powers.", "دائیں جانب کو اسی اساس کی طاقت میں لکھ کر طاقتیں برابر کریں۔",
                  f"{base}**({ps(k)}) == {ps(v)}")], [x0]
    return run


def recip_eq(sign, v):
    """x + 1/x = v (sign '+') or x - 1/x = v (sign '-') -> quadratic in x."""
    def run():
        poly = sp.expand(X ** 2 - v * X + (1 if sign == "+" else -1))
        den = sp.ilcm(*[sp.fraction(c)[1] for c in sp.Poly(poly, X).all_coeffs()])
        poly = sp.expand(poly * den)
        st = [S(rf"x {sign} \frac{{1}}{{x}} = {sp.latex(v)} \Rightarrow {sp.latex(poly)} = 0", "Multiply by $x$ (and clear fractions).", "$x$ سے ضرب دیں (اور کسور ختم کریں)۔",
                f"expand((x {sign} 1/x - {ps(v)})*x*{den}) == {ps(poly)}")]
        more, rs = back_quadratic(sp.sstr(poly))
        return st + more, rs
    return run


