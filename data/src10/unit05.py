def solve_y(poly_y):
    """Solve the quadratic in y by factorization (or the formula when it does not factor)."""
    p = sp.expand(sp.sympify(poly_y, locals={"y": Y}))
    D = sp.discriminant(p, Y)
    st, roots = (factor_steps(p, Y) if D >= 0 and sp.sqrt(D).is_Rational else formula_steps(p, Y))
    return st, roots


def back_quadratic(poly_x):
    """Solve a quadratic in x, by factorization when possible, else the formula; complex roots are written with i."""
    p = sp.expand(sp.sympify(poly_x, locals={"x": X}))
    D = sp.discriminant(p, X)
    if D >= 0 and sp.sqrt(D).is_Rational:
        return factor_steps(p, X)
    if D >= 0:
        return formula_steps(p, X)
    a, b, c = sp.Poly(p, X).all_coeffs()
    r1, r2 = (-b + sp.sqrt(D)) / (2 * a), (-b - sp.sqrt(D)) / (2 * a)
    steps = [S(rf"x = \frac{{-({b}) \pm \sqrt{{({b})^2 - 4({a})({c})}}}}{{2({a})}} = \frac{{{-b} \pm \sqrt{{{D}}}}}{{{2 * a}}} = \frac{{{-b} \pm i\sqrt{{{-D}}}}}{{{2 * a}}}",
               "Quadratic formula; the number under the root is negative, so these two roots are complex ($\\sqrt{-1} = i$).",
               "دو درجی کلیہ؛ جذر کے نیچے عدد منفی ہے، اس لیے یہ دو جذر مختلط ہیں ($\\sqrt{-1} = i$)۔",
               f"({sp.sstr(p)}).subs(x, {ps(r1)}) == 0", f"({sp.sstr(p)}).subs(x, {ps(r2)}) == 0")]
    return steps, [r1, r2]


def reducible(label, prompt, original_py, pre, poly_y, ysub_tex, backs, answer_roots=None, note=None):
    """pre: (tex, en, ur, checks) lines that reach the quadratic in y; backs: {y value: (tex for 'sub = value', poly_x or callback)}."""
    steps = [S(t, en, ur, *c) for t, en, ur, c in pre]
    st, yroots = solve_y(poly_y)
    steps += st[1:]
    roots = []
    for yv in yroots:
        line, how = backs[yv]
        if callable(how):
            more, rs = how()
            more[0] = {**more[0], "en": f"Put back ${ysub_tex}$: " + more[0]["en"], "ur": f"${ysub_tex}$ واپس رکھیں: " + more[0]["ur"]}
        else:
            steps.append(S(line, f"Put back ${ysub_tex}$.", f"${ysub_tex}$ واپس رکھیں۔"))
            more, rs = back_quadratic(how)
        steps += more
        roots += rs
    roots = answer_roots or roots
    checks = [f"simplify(({original_py}).subs(x, {ps(r)})) == 0" for r in roots]
    shown = ", ".join(rtex(r) for r in roots)
    steps.append(S(rf"\text{{S.S}} = \{{{shown}\}}", "Every root satisfies the given equation.", "ہر جذر دی گئی مساوات کو پورا کرتا ہے۔", *checks))
    part = P(label, steps, "$x = " + r",\ ".join(rtex(r) for r in roots) + "$", prompt=prompt)
    if note:
        part["key_note"] = note
    return part


def rtex(r):
    """A real root as students write it; a complex root as (p + i q)/d."""
    r = sp.nsimplify(r)
    if sp.im(r) == 0:
        return tex_root(r)
    d = sp.fraction(sp.together(r))[1]
    n = sp.expand(r * d)
    a, b = sp.re(n), sp.im(n)
    body = f"{sp.latex(a)} {'-' if b < 0 else '+'} i{sp.latex(abs(b))}"
    return body if d == 1 else rf"\frac{{{body}}}{{{sp.latex(d)}}}"


